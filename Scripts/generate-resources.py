#!/usr/bin/env python3
"""Generate native localization resources from the shared UTF-8 catalogs."""

import argparse
import hashlib
import json
from pathlib import Path
import plistlib
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
CATALOGS = ROOT / "Shared/Resources/Localization"


def resource_id(key):
    return "Text_" + hashlib.sha256(key.encode("utf-8")).hexdigest()[:24]


def windows_format(value):
    position = 0

    def replace(match):
        nonlocal position
        index = int(match[1]) - 1 if match[1] else position
        position += 1
        return "{" + str(index) + "}"

    return re.sub(r"%(?:(\d+)\$)?(?:lld|ld|d|u|@)", replace, value.replace("{", "{{").replace("}", "}}"))


def outputs():
    inputs = []
    catalogs = {source.stem: json.loads(source.read_text(encoding="utf-8"))
                for source in sorted(CATALOGS.glob("*.json"))}
    for language, catalog in catalogs.items():
        inputs.extend([
            f"$(SRCROOT)/../../Shared/Resources/Localization/{language}.json",
            f"$(SRCROOT)/Resources/{language}.lproj/Localizable.strings",
            f"$(SRCROOT)/Resources/{language}.lproj/Localizable.stringsdict",
            f"$(SRCROOT)/../Windows/src/FoldGit.App/Strings/{language}/Resources.resw",
        ])
        apple = ROOT / f"Platforms/macOS/Resources/{language}.lproj"
        text = "/* Generated by Scripts/generate-resources.py. Edit Shared/Resources/Localization. */\n\n"
        text += "\n".join(f"{json.dumps(key, ensure_ascii=False)} = {json.dumps(value, ensure_ascii=False)};"
                          for key, value in sorted(catalog["strings"].items())) + "\n"
        yield apple / "Localizable.strings", text.encode("utf-8")
        yield apple / "Localizable.stringsdict", plistlib.dumps(catalog["plurals"], sort_keys=True)
        resource = ET.Element("root")
        for name, value in [("resmimetype", "text/microsoft-resx"), ("version", "2.0")]:
            ET.SubElement(ET.SubElement(resource, "resheader", name=name), "value").text = value
        values = dict(catalog["strings"])
        values.update(catalog.get("windows", {}))
        for key, entry in catalog["plurals"].items():
            for category, value in entry["count"].items():
                if not category.startswith("NSString"):
                    values[key + ":" + category] = value
            if language == "en":
                # Every localized PRI key needs a default-language candidate, including Russian plural forms.
                categories = {category for translation in catalogs.values()
                              for category in translation["plurals"][key]["count"]
                              if not category.startswith("NSString")}
                for category in categories:
                    values.setdefault(key + ":" + category, entry["count"]["other"])
        for key, value in sorted(values.items()):
            data = ET.SubElement(resource, "data", name=resource_id(key))
            data.set("xml:space", "preserve")
            ET.SubElement(data, "value").text = windows_format(value)
        for key, value in [("AppDisplayName", "FoldGit"), ("AppDescription", values["Git Client"])]:
            ET.SubElement(ET.SubElement(resource, "data", name=key), "value").text = value
        ET.indent(resource)
        yield ROOT / f"Platforms/Windows/src/FoldGit.App/Strings/{language}/Resources.resw", ET.tostring(resource, encoding="utf-8", xml_declaration=True) + b"\n"
    yield ROOT / "Scripts/SharedResources.xcfilelist", ("\n".join(inputs) + "\n").encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    stale = []
    for path, content in outputs():
        if arguments.check:
            if not path.exists() or path.read_bytes() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            if not path.exists() or path.read_bytes() != content:
                path.write_bytes(content)
    if stale:
        raise SystemExit("Generated resources are stale. Run python3 Scripts/generate-resources.py:\n" + "\n".join(stale))
    print("Validated shared localization outputs" if arguments.check else "Generated native localization resources")


if __name__ == "__main__":
    main()
